def find_group(species: str):
    if not species:
        return None
    for group in GROUPS.values():
        for s in group["species"]:
            if s in species or species in s:
                return group
    return None


def get_preset_advice(species: str, kind: str):
    group = find_group(species)
    if not group:
        return None
    info = group[kind]
    return {
        "source": "preset",
        "emoji": group["emoji"],
        "title": f"{group['title']} ({species})",
        **info,
    }


def get_advice(species: str, kind: str, language: str = "ko"):
    """species/kind에 맞는 비료 추천을 돌려준다. 프리셋 그룹에 없으면 AI에게 그 자리에서 물어보고
    세션 동안 결과를 캐싱해 같은 작물을 여러 번 볼 때 다시 호출하지 않는다."""
    preset = get_preset_advice(species, kind)
    if preset:
        return preset

    if "fertilizer_cache" not in st.session_state:
        st.session_state.fertilizer_cache = {}

    cache_key = f"{kind}::{species}::{language}"
    if cache_key not in st.session_state.fertilizer_cache:
        with st.spinner(f"AI가 '{species}'에 맞는 비료를 찾고 있어요..."):
            st.session_state.fertilizer_cache[cache_key] = ai.generate_fertilizer_advice(species, kind, language=language)

    result = st.session_state.fertilizer_cache[cache_key]
    if not result:
        return None
    return {
        "source": "ai",
        "emoji": "🌱",
        "title": f"{species} 맞춤 추천 (AI)",
        **result,
    }
